// Copies the built SPA shell into a JS module so /api/render can use it.
import { readFile, writeFile } from 'node:fs/promises';
const html = await readFile(new URL('../dist/index.html', import.meta.url), 'utf8');
await writeFile(
  new URL('../api/_lib/template.generated.js', import.meta.url),
  `// Generated by scripts/write-template.mjs at build time. Do not edit.\nexport default ${JSON.stringify(html)};\n`
);
// Move the shell off /index.html so Vercel does not serve it statically for "/",
// letting the "/" rewrite reach /api/render (crawlable homepage).
const { rename } = await import('node:fs/promises');
await rename(new URL('../dist/index.html', import.meta.url), new URL('../dist/app.html', import.meta.url));
console.log('[write-template] api/_lib/template.generated.js written; dist/index.html -> dist/app.html');
