<h3>Portable first aid kit</h3>
<p>A compact first aid kit is essential for any trip. Make sure it contains plasters, antiseptic, painkillers (paracetamol or ibuprofen), allergy medicine and something for nausea and motion sickness.</p>
<h3>Reusable filter water bottle</h3>
<p>A filter bottle keeps you hydrated and is better for the environment. Some come with a built-in filter that removes impurities and chlorine, so you can refill from any tap.</p>
<p>Check that tap water is safe to use with your filter at your destination. Recommended brands: LARQ, Brita, Grayl.</p>

<h2>Security and privacy</h2>
<h3>Portable door lock</h3>
<p>A portable door lock adds an extra layer of security in hotels or Airbnb flats. It fits on the inside of your room door and cannot be opened from outside, even by someone with a key.</p>
<p>It is light and small, so it slips easily into your bag.</p>
<h3>RFID-blocking wallet</h3>
<p>An RFID wallet protects your bank cards and passport from electronic theft. It blocks radio signals so your card details cannot be read remotely.</p>
<p>A small investment for a lot of protection.</p>
<h3>Digital luggage scale</h3>
<p>A small digital scale lets you weigh your bag before you leave for the airport. It can save you a lot of money by helping you avoid excess baggage fees.</p>
<p>Most are about the size of your palm and fit easily in your hand luggage.</p>

