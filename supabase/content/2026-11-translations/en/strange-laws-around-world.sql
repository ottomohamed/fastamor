<h2>Singapore: the chewing gum ban</h2>
<h3>No importing or chewing gum</h3>
<p>Importing or chewing gum has been banned in Singapore since 1992. The strict rule was introduced to keep public spaces and the city's modern transport system clean.</p>
<p>You could face heavy fines if you are found with commercial quantities without a medical permit. Singaporeans take cleanliness seriously, and the law reflects their commitment to keeping the city one of the cleanest in the world.</p>
<p><strong>Warning:</strong> on-the-spot fines can reach 1,000 Singapore dollars.</p>

<h2>Italy (Venice): feeding pigeons is off limits</h2>
<h3>Venice: do not feed the pigeons</h3>
<p>Feeding pigeons in St Mark's Square in Venice is strictly prohibited. The rule aims to protect statues and historic buildings from damage caused by bird droppings.</p>
<p>Feeding draws large flocks, and their droppings wear away the limestone of the square's statues and buildings. Fines can run to hundreds of euros.</p>
<p><strong>Warning:</strong> fines start at 50 euros and can reach 500 euros.</p>

<h2>Greece: no high heels at archaeological sites</h2>
<h3>High heels are banned at the Acropolis</h3>
<p>To protect ancient marble from wear, the Greek authorities ban high-heeled shoes at sites such as the Acropolis. Sharp heels can crack and wear down stones that are thousands of years old.</p>
<p>Choose comfortable, flat shoes so you are not turned away at the entrance.</p>
<p><strong>Tip:</strong> trainers or flat shoes are the best choice for visiting archaeological sites.</p>

<h2>Germany: running out of fuel is against the rules</h2>
<h3>Germany: an empty tank on the Autobahn</h3>
<p>Running out of fuel on the Autobahn is not just bad luck: it breaks the law. Stopping unnecessarily on the motorway is treated as a safety hazard and can lead to a fine.</p>
<p>The rule exists to protect all road users, because a car stranded without fuel is a serious danger in fast-moving traffic.</p>
<p><strong>Tip:</strong> always check your fuel level before setting off on the Autobahn.</p>

<h2>Sri Lanka: respect for sacred images and the selfie rule</h2>
<h3>Sri Lanka: no selfies with Buddha statues</h3>
<p>Turning your back on a statue of the Buddha to take a selfie is considered deeply disrespectful and can lead to arrest. Always face the statue when taking photos, as a sign of respect for the local culture.</p>
<p>Sri Lanka is a majority-Buddhist country, and the Buddha is a sacred figure who must be treated with full respect.</p>
<p><strong>Warning:</strong> breaking this rule can lead to arrest and a fine.</p>

<h2>Switzerland: night-time quiet and the toilet flush</h2>
<h3>Switzerland: quiet hours in apartment buildings</h3>
<p>In many Swiss apartment buildings, house rules (customary and sometimes written) discourage flushing the toilet after 10 pm to avoid noise. This is a building rule rather than a national law, so check the rules where you stay.</p>
<p>The Swiss value privacy and calm above almost everything else. The golden rule is quiet from 10 pm to 7 am.</p>
<p><strong>Tip:</strong> respect quiet hours in residential buildings.</p>

<h2>Spain: no swimwear away from the beach</h2>
<h3>Spain: beachwear stays on the beach</h3>
<p>In several Spanish coastal cities, such as Barcelona and Málaga, walking around the streets in swimwear (swimming costumes and bikinis) away from the beach is banned. The aim is to maintain public decorum and the look of the city.</p>
<p>People who break the rule may be fined.</p>
<p><strong>Warning:</strong> fines range from about 100 to 500 euros, depending on the city. Check current local rules.</p>

<h2>Thailand: respect for the king and the currency</h2>
<h3>Thailand: never step on money</h3>
<p>In Thailand, stepping on or otherwise insulting the local currency, the baht, is an offence punishable by law.</p>
<p>Banknotes and coins carry the king's image, so any disrespect towards them is seen as disrespect towards the royal family, which is held in very high regard in Thai society.</p>

