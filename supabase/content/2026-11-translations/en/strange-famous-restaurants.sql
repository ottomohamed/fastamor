<h2>1. Ithaa Undersea Restaurant, Maldives</h2>
<h3>Five metres below the surface of the Indian Ocean</h3>
<p>Ithaa sits about 5 metres below sea level at the Conrad Maldives Rangali Island resort. Its curved glass gives 180-degree views of coral gardens and busy marine life.</p>
<p>You eat while sharks and stingrays glide directly over your head. The room seats only 16 guests, so you need to book months ahead. The menu includes fresh oysters, Wagyu beef and local Indian Ocean fish.</p>
<p><strong>Approximate price:</strong> 400 to 700 US dollars per person.</p>

<h2>2. Dinner in the Sky: Dubai, London and Paris</h2>
<h3>Fifty metres up in the air</h3>
<p>This one defies gravity. The dining table, the chef and the serving staff are lifted about 50 metres into the air by a large crane.</p>
<p>The experience runs in major cities such as Dubai, London and Paris, with a bird's-eye view over the skyline. Guests are strapped in with safety harnesses and served a meal of five to seven courses with fine wines.</p>
<p><strong>Approximate price:</strong> 300 to 600 US dollars per person.</p>

<h2>3. Grotta Palazzese, Italy</h2>
<h3>Polignano a Mare, inside a natural cave</h3>
<p>This restaurant is set inside a natural limestone cave that opens straight onto the Adriatic Sea. Its history goes back to the 1700s, when the cave hosted lavish parties for the nobility.</p>
<p>You look out over waves breaking on the rocks, and candlelight gives the place a romantic feel. The kitchen serves fresh seafood and traditional Italian dishes.</p>
<p><strong>Approximate price:</strong> 200 to 400 euros per person.</p>

<h2>4. The Rock, Zanzibar</h2>
<h3>Zanzibar, Tanzania: on a rock in the ocean</h3>
<p>This small restaurant sits on top of a lone rock in the Indian Ocean. How you get there depends on the tide: at low tide you can walk across, and at high tide you take a small boat.</p>
<p>The menu focuses on fresh seafood such as lobster, crab and squid, served in a quiet, secluded setting.</p>
<p><strong>Approximate price:</strong> 80 to 150 US dollars per person.</p>

<h2>5. Giraffe Manor, Nairobi, Kenya</h2>
<h3>Breakfast with giraffes</h3>
<p>At Giraffe Manor in Nairobi, endangered Rothschild's giraffes join you for breakfast by stretching their long necks through the windows of this classic house.</p>
<p>The manor dates from the 1930s and is built in British colonial style. Guests stay in the manor itself, which is a small luxury boutique hotel, and breakfast with the giraffes is the moment everyone waits for.</p>
<p><strong>Approximate price:</strong> 500 to 1,000 US dollars per night, including accommodation and breakfast.</p>

<h2>6. Le Jaggernau, Malaysia</h2>
<h3>Malaysia: dining under a green canopy</h3>
<p>This restaurant sits beneath a natural canopy of large trees in Penang National Park. The design is completely open, so the forest becomes part of the meal.</p>
<p>It serves authentic Malaysian and Thai cuisine, and the natural setting makes the experience unlike any city restaurant. It is reported to rank among the top 10 Asian restaurants in the world.</p>

