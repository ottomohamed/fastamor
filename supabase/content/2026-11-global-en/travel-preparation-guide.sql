<h2>Three Months or More Before You Travel</h2>
<h3>Check Your Passport</h3>
<ul>
<li>Many countries require your passport to be valid for at least <strong>three to six months beyond your planned departure date</strong>. Schengen countries require at least three months beyond the date you intend to leave the Schengen Area, and the passport must have been issued within the previous ten years.</li>
<li>Make sure you have enough blank pages for stamps and visas.</li>
<li>Passport renewal can take several weeks, longer in peak season or if you apply through a consulate abroad, so start early.</li>
<li>Children need their own passports, and some countries ask for a parental consent letter if a minor travels without both parents.</li>
</ul>
<h3>Find Out Whether You Need a Visa or Travel Authorisation</h3>
<p>Entry requirements depend on your nationality, your residence status and the purpose of your trip. Many countries now use online travel authorisations for visitors who do not need a full visa:</p>
<ul>
<li><strong>Schengen Area (France, Spain, Italy, Germany and others):</strong> citizens of many countries, including the UK, the USA, Canada, Australia, Japan and Singapore, can usually visit visa-free for up to 90 days in any 180-day period. Others, for example Indian, Chinese or Moroccan passport holders, generally need a short-stay Schengen visa, which can usually be requested up to six months and at least 15 days before travel.</li>
<li><strong>EU digital borders:</strong> the EU's Entry/Exit System registers non-EU visitors at the border, and the ETIAS travel authorisation for visa-exempt travellers is due to follow. Check the official EU website for the current start date.</li>
<li><strong>United Kingdom:</strong> the UK is outside Schengen. Many visa-exempt visitors, including EU, US and Australian citizens, now need an Electronic Travel Authorisation (ETA), while other nationalities need a visitor visa.</li>
<li><strong>United States, Canada and Australia:</strong> eligible visitors apply online in advance, through ESTA for the USA, an eTA for Canada when flying in, or an ETA or eVisitor for Australia. Others need a visa.</li>
<li><strong>Elsewhere:</strong> rules vary widely. Some countries offer e-visas, some visas on arrival, and some require a visa in advance.</li>
</ul>
<p>Always use official government websites and accredited visa providers. Beware of unofficial sites that charge extra fees.</p>
<h3>Set Your Budget</h3>
<p>List your main costs: flights, accommodation, local transport, food, activities, insurance, visa or authorisation fees and a buffer for unexpected expenses. Many travellers add an emergency margin of around 10–20% of the total budget. Prices change by season, so compare dates if you are flexible.</p>

<h2>One to Two Months Before</h2>
<h3>Book the Essentials</h3>
<ul>
<li>Flights, ferries or long-distance trains. School holidays and major festivals push prices up and fill seats early.</li>
<li>Accommodation, especially in high season or during festivals and major events.</li>
<li>Timed-entry attractions that sell out, such as the Alhambra, the Vatican Museums, the Sagrada Família and the Last Supper in Milan.</li>
<li>Airport transfers or car hire, particularly if you arrive late at night.</li>
</ul>
<h3>Buy Travel Insurance</h3>
<p>Choose a policy that covers medical emergencies, repatriation, cancellation and lost luggage. It is mandatory for Schengen visa applications and strongly recommended for every trip. Check exclusions for pre-existing conditions, sports and electronics.</p>
<h3>Health Preparation</h3>
<p>See your doctor or a travel clinic four to eight weeks before departure for vaccines and medical advice, renew prescriptions, and check whether your medicines are allowed at your destination. Official sources such as the CDC, the WHO and NHS Fit for Travel list country-by-country recommendations.</p>

<h2>Two to Three Weeks Before</h2>
<h3>Money and Payments</h3>
<ul>
<li>Tell your bank you will be travelling, if required, and check foreign transaction and ATM fees.</li>
<li>Carry at least two payment methods, such as a debit card and a credit card, kept in separate places.</li>
<li>Have a small amount of local currency for arrival, taxis and tips. Some currencies are easier and cheaper to obtain once you arrive.</li>
<li>Find out whether your destination is mainly card-based (much of northern Europe, Australia and Singapore) or still relies on cash (many markets, rural areas and small shops worldwide).</li>
<li>When paying by card abroad, choosing to pay in the local currency rather than your home currency often avoids poor conversion rates.</li>
</ul>
<h3>Phone and Internet</h3>
<ul>
<li>Check your roaming plan. EU "roam like at home" rules apply only to EU-based plans within the EU, and roaming elsewhere can be expensive.</li>
<li>Consider a local SIM card or a travel eSIM, which you can often buy and install before you leave.</li>
<li>Download offline maps, translation apps, airline apps and your booking confirmations.</li>
</ul>
